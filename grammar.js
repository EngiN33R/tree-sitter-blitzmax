// Case-insensitive BlitzMax NG. Expressions are deliberately permissive:
// semantic validation belongs to bls, while incomplete code stays useful in Zed.
const ci = s => new RegExp([...s].map(c => /[a-z]/i.test(c) ? `[${c.toLowerCase()}${c.toUpperCase()}]` : c).join(''));
const kw = ($, s) => alias(token(prec(2, ci(s))), $.keyword);
const end = ($, s) => alias(token(prec(3, new RegExp(ci('End').source + '[ \\t]*' + ci(s).source))), $.keyword);

module.exports = grammar({
  name: 'blitzmax',
  word: $ => $.identifier,
  extras: $ => [/[ \t\f\uFEFF]/, $.comment, $.line_continuation],
  externals: $ => [$.block_comment, $.multiline_string],
  rules: {
    source_file: $ => seq(repeat($._statement), optional($.final_statement)),
    _newline: _ => /\r?\n/,
    _end_of_line: $ => choice($._newline, ';'),
    _statement: $ => choice(
      $._newline, ';', $.block_comment,
      $.type_definition, $.struct_definition, $.interface_definition,
      $.enum_definition, $.extern_block,
      $.function_definition, $.method_definition,
      $.abstract_method, $.abstract_function,
      $.import_statement, $.include_statement, $.module_statement,
      $.variable_declaration, $.simple_statement,
    ),
    type_definition: $ => seq(kw($, 'Type'), field('name', $.identifier), repeat($._part), $._end_of_line,
      repeat($._statement), end($, 'Type')),
    struct_definition: $ => seq(kw($, 'Struct'), field('name', $.identifier), repeat($._part), $._end_of_line,
      repeat($._statement), end($, 'Struct')),
    interface_definition: $ => seq(kw($, 'Interface'), field('name', $.identifier), repeat($._part), $._end_of_line,
      repeat(choice($._newline, $.block_comment, $.function_signature, $.method_signature)), end($, 'Interface')),
    enum_definition: $ => seq(kw($, 'Enum'), field('name', $.identifier), repeat($._part), $._end_of_line,
      repeat($._statement), end($, 'Enum')),
    extern_block: $ => seq(kw($, 'Extern'), repeat($._part), $._end_of_line,
      repeat(choice($._newline, $.block_comment, $.function_signature, $.variable_declaration, $.simple_statement)), end($, 'Extern')),
    function_definition: $ => seq(kw($, 'Function'), field('name', $.identifier), repeat($._part), $._end_of_line,
      repeat($._statement), end($, 'Function')),
    method_definition: $ => seq(kw($, 'Method'), optional(kw($, 'Operator')), field('name', choice($.identifier, $.operator, $.square_group)), repeat($._part), $._end_of_line,
      repeat($._statement), end($, 'Method')),
    abstract_function: $ => seq(kw($, 'Function'), field('name', $.identifier), repeat($._part), kw($, 'Abstract'), $._end_of_line),
    abstract_method: $ => seq(kw($, 'Method'), field('name', $.identifier), repeat($._part), kw($, 'Abstract'), $._end_of_line),
    function_signature: $ => seq(kw($, 'Function'), field('name', $.identifier), repeat($._part), optional(kw($, 'Abstract')), $._end_of_line),
    method_signature: $ => seq(kw($, 'Method'), field('name', $.identifier), repeat($._part), optional(kw($, 'Abstract')), $._end_of_line),
    import_statement: $ => seq(kw($, 'Import'), repeat1($._part), $._end_of_line),
    include_statement: $ => seq(kw($, 'Include'), $.string, $._end_of_line),
    module_statement: $ => seq(kw($, 'Module'), repeat1($._part), $._end_of_line),
    variable_declaration: $ => seq(field('storage', choice(kw($, 'Local'), kw($, 'Global'), kw($, 'Const'), kw($, 'Field'))), field('name', $.identifier), repeat($._part), $._end_of_line),
    simple_statement: $ => seq(repeat1($._part), $._end_of_line),
    final_statement: $ => repeat1($._part),
    _part: $ => choice($.identifier, $.keyword, $.builtin_type, $.boolean, $.null,
      $.number, $.string, $.multiline_string, $.operator, $.punctuation,
      $.parenthesized_group, $.square_group, $.brace_group, $.preprocessor),
    parenthesized_group: $ => seq('(', repeat($._part), ')'),
    square_group: $ => seq('[', repeat($._part), ']'),
    brace_group: $ => seq('{', repeat($._part), '}'),
    identifier: _ => /[A-Za-z_][A-Za-z_0-9]*/,
    keyword: _ => token(prec(1, choice(...[
      'Strict', 'SuperStrict', 'Framework', 'ModuleInfo', 'ModulePrivate',
      'If', 'Then', 'Else', 'ElseIf', 'EndIf', 'Select', 'Case', 'Default', 'EndSelect',
      'For', 'To', 'Until', 'Step', 'Next', 'EachIn', 'While', 'Wend', 'EndWhile',
      'Repeat', 'Forever', 'Exit', 'Continue', 'Return', 'End',
      'Try', 'Catch', 'Finally', 'EndTry', 'Throw', 'Assert',
      'Public', 'Private', 'Protected', 'Extends', 'Implements', 'Final', 'Override',
      'New', 'Delete', 'Self', 'Super', 'Ptr', 'Var', 'VarPtr', 'Chr', 'Asc',
      'Len', 'SizeOf', 'Incbin', 'IncbinPtr', 'IncbinLen',
      'ReadData', 'RestoreData', 'DefData', 'Release', 'DebugStop', 'DebugLog',
    ].map(ci)))),
    builtin_type: _ => token(prec(2, choice(...[
      'Byte', 'Short', 'Int', 'UInt', 'Long', 'ULong', 'Size_T', 'Float', 'Double',
      'String', 'Object', 'Void', 'Int128', 'Float64', 'Float128', 'Double128', 'Double256',
    ].map(ci)))),
    boolean: _ => token(prec(2, choice(ci('True'), ci('False')))),
    null: _ => token(prec(2, ci('Null'))),
    number: _ => token(choice(/\$[0-9a-fA-F]+/, /%[01]+/,
      /[0-9]+(\.[0-9]*)?([eE][+-]?[0-9]+)?/, /\.[0-9]+([eE][+-]?[0-9]+)?/)),
    string: $ => seq('"', repeat(choice($.escape_sequence, $.string_content)), '"'),
    string_content: _ => token.immediate(prec(4, /[^"~\r\n]+/)),
    escape_sequence: _ => token.immediate(/~([qQnNrRtT0~]|[uU][0-9a-fA-F]{4})/),
    operator: _ => token(choice(...[
      'And', 'Or', 'Not', 'Mod', 'Shl', 'Shr', 'Sar', 'Xor',
    ].map(ci), /:[+*/&|~^-]/, ':Mod', ':mod', ':Shl', ':shl', ':Shr', ':shr',
      '<=', '>=', '<>', '..', '+', '-', '*', '/', '=', '<', '>', '&', '|', '~', '^')),
    punctuation: _ => /[,:.!#$%@\\]/,
    preprocessor: _ => token(seq('?', /[^\r\n]*/)),
    comment: _ => token(seq("'", /[^\r\n]*/)),
    line_continuation: _ => token(prec(3, /\.\.[ \t]*(\x27[^\r\n]*)?\r?\n/)),
  },
});
